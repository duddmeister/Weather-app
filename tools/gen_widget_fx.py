"""Generates the widget sky-effect vector drawables: still versions of the app's animated sky.

    python3 tools/gen_widget_fx.py [output dir, default app/src/main/res/drawable]

Even fields (stars, rain, snow, lightning) are 400x220 and centre-cropped to each widget. Clouds and
fog follow the widget's edges, so they're stretched to fit; clouds come in wide (400x110), standard
(400x220) and square (300x300) versions, picked by the widget's shape (see SkyEffect). The sun and
moon glows are 180x180 and sit in the widget's top-end corner. Positions are seeded, so output is stable.
"""
import random
import sys
from pathlib import Path

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "app/src/main/res/drawable")
W, H = 400, 220
# Lint flags path data longer than 800 characters, so many shapes are spread over several paths.
MAX_PATH = 760

HEADER = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_widget_fx.py: widget sky effect ({name}). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{w}dp"
    android:height="{h}dp"
    android:viewportWidth="{w}"
    android:viewportHeight="{h}">
'''
FOOTER = '</vector>\n'


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0"


def chunks(shapes):
    """Joins shape path data into strings of at most MAX_PATH characters."""
    out, current = [], ""
    for shape in shapes:
        if current and len(current) + len(shape) > MAX_PATH:
            out.append(current)
            current = ""
        current += shape
    return out + [current] if current else out


def path(shapes, color="#FFFFFF", alpha=1.0):
    return "".join(f'    <path android:fillColor="{color}" android:fillAlpha="{alpha:.2f}" android:pathData="{d}" />\n'
                   for d in chunks(shapes))


def stroke_path(shapes, alpha, width):
    return "".join(f'    <path android:strokeColor="#FFFFFF" android:strokeAlpha="{alpha:.2f}" android:strokeWidth="{width}" '
                   f'android:strokeLineCap="round" android:pathData="{d}" />\n' for d in chunks(shapes))


def radial(cx, cy, r, color, alpha_center, w=W, h=H):
    a = int(round(alpha_center * 255))
    return f'''    <path android:pathData="M0,0h{w}v{h}h-{w}z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{f(cx)}" android:centerY="{f(cy)}" android:gradientRadius="{f(r)}">
                <item android:offset="0" android:color="#{a:02X}{color}" />
                <item android:offset="1" android:color="#00{color}" />
            </gradient>
        </aapt:attr>
    </path>
'''


def band(y0, y1, alpha):
    a = int(round(alpha * 255))
    return f'''    <path android:pathData="M0,{f(y0)}h{W}v{f(y1 - y0)}h-{W}z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="{f(y0)}" android:endX="0" android:endY="{f(y1)}">
                <item android:offset="0" android:color="#00FFFFFF" />
                <item android:offset="0.5" android:color="#{a:02X}FFFFFF" />
                <item android:offset="1" android:color="#00FFFFFF" />
            </gradient>
        </aapt:attr>
    </path>
'''


def write(name, body, w=W, h=H):
    (OUT / f"{name}.xml").write_text(HEADER.format(name=name, w=w, h=h) + body + FOOTER)


def stars():
    rnd = random.Random(7)
    buckets = {0.3: [], 0.45: [], 0.65: [], 0.8: []}
    glows = ""
    for i in range(70):
        x, y = rnd.uniform(6, W - 6), rnd.uniform(5, H - 5)
        u = rnd.random()
        r = 0.45 + 1.0 * u * u
        alpha = min(buckets, key=lambda a: abs(a - (0.25 + 0.6 * u)))
        buckets[alpha].append(circle(x, y, r))
    for _ in range(5):  # a few brighter stars with a halo
        x, y = rnd.uniform(20, W - 20), rnd.uniform(12, H - 12)
        glows += radial(x, y, 6, "FFFFFF", 0.28)
        buckets[0.8].append(circle(x, y, 1.6))
    body = glows + "".join(path(c, alpha=a) for a, c in buckets.items() if c)
    write("fx_stars", body)


def soft_lobe(cx, cy, r, alpha):
    """A circle with a feathered edge; overlapping lobes build up into a soft, puffy cloud."""
    def argb(k):
        return f"#{int(round(alpha * k * 255)):02X}FFFFFF"
    return f'''    <path android:pathData="{circle(cx, cy, r)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{f(cx)}" android:centerY="{f(cy)}" android:gradientRadius="{f(r)}">
                <item android:offset="0" android:color="{argb(1)}" />
                <item android:offset="0.6" android:color="{argb(0.85)}" />
                <item android:offset="1" android:color="#00FFFFFF" />
            </gradient>
        </aapt:attr>
    </path>
'''


# The app's cloud: five soft circles (x, y, radius) around its centre, in dp at scale 1.
LOBES = [(-70, 12, 46), (-28, -10, 58), (26, -4, 54), (72, 12, 42), (0, 22, 60)]


def cloud(cx, cy, scale, alpha):
    return "".join(soft_lobe(cx + dx * scale, cy + dy * scale, r * scale, alpha) for dx, dy, r in LOBES)


# Cropping would cut clouds at the edges down to their tips on short widgets, so each shape gets its own.
SHAPES = {"_wide": (400, 110), "": (400, 220), "_square": (300, 300)}


def clouds(name, layout, alpha):
    """layout(w, h) lists (x, y, scale) for each cloud on a w x h canvas."""
    for suffix, (w, h) in SHAPES.items():
        write(name + suffix, "".join(cloud(x, y, s, alpha) for x, y, s in layout(w, h)), w, h)


def light_clouds(w, h):
    # One cloud drifting in the top-end corner and one low in the bottom-start corner.
    s = min(h / 220, 1.0) * 0.75 + 0.15
    return [(w - 85 * s - 10, 6, s), (60 * s + 10, h + 4, s * 0.9)]


def heavy_clouds(w, h):
    # A deck along the top and a lower bank along the bottom.
    s = min(h / 220, 1.0) * 0.7 + 0.25
    end = int(w + 110 * s)  # a cloud reaches about 115*s either side of its centre
    top = [(x, -4 + 10 * (i % 2), s * (1.0 if i % 2 else 0.9)) for i, x in enumerate(range(-20, end, int(130 * s)))]
    bottom = [(x, h + 14, s * 0.8) for x in range(int(40 * s), end, int(170 * s))]
    return top + bottom


def rain(name, count, length, alpha_levels, width, seed):
    rnd = random.Random(seed)
    segs = {a: [] for a in alpha_levels}
    for _ in range(count):
        x, y = rnd.uniform(-20, W + 10), rnd.uniform(-10, H)
        ln = rnd.uniform(*length)
        dx = -0.22 * ln  # slanted as if blown by a light wind
        segs[rnd.choice(alpha_levels)].append(f"M{f(x)},{f(y)}l{f(dx)},{f(ln)}")
    write(name, "".join(stroke_path(s, a, width) for a, s in segs.items() if s))


def snow():
    rnd = random.Random(11)
    buckets = {0.4: [], 0.55: [], 0.75: []}
    for _ in range(75):
        x, y = rnd.uniform(4, W - 4), rnd.uniform(4, H - 4)
        u = rnd.random()
        r = 0.8 + 1.4 * u
        alpha = 0.4 if u < 0.33 else 0.55 if u < 0.7 else 0.75
        buckets[alpha].append(circle(x, y, r))
    write("fx_snow", "".join(path(c, alpha=a) for a, c in buckets.items()))


def fog():
    write("fx_fog", band(36, 92, 0.16) + band(96, 154, 0.19) + band(146, 206, 0.13))


def lightning():
    bolt = "M250,6L229,84L245,84L230,170L270,70L252,70L266,6Z"
    body = radial(248, 80, 105, "FFFFFF", 0.14)
    body += path([bolt], color="#F4F2FF", alpha=0.4)
    write("fx_lightning", body)


def glow(name, color, alpha, core):
    # Anchored in the widget's top-end corner by the layout; the light sits up in that corner.
    body = radial(156, 18, 124, color, alpha, 180, 180)
    if core:
        body += radial(156, 18, 44, "FFF4D0", core, 180, 180)
    write(name, body, 180, 180)


stars()
clouds("fx_clouds_light", light_clouds, 0.2)
clouds("fx_clouds_heavy", heavy_clouds, 0.16)
rain("fx_rain", 80, (10, 16), [0.16, 0.24, 0.32], 0.9, 3)
rain("fx_rain_heavy", 160, (14, 24), [0.15, 0.22, 0.3], 1.0, 5)
snow()
fog()
lightning()
glow("fx_sun_glow", "FFE6A3", 0.48, 0.34)
glow("fx_moon_glow", "DDE6FF", 0.22, 0.0)
print(f"Wrote widget effects to {OUT}")
